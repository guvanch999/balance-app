-- Balances are stored as integer minor units (e.g. cents) to avoid floating point.
-- The CHECK constraint is a second line of defence: even a buggy query cannot
-- leave a balance below zero, Postgres will reject the write.
CREATE TABLE users (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  balance    bigint NOT NULL DEFAULT 0 CONSTRAINT balance_non_negative CHECK (balance >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tasks (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL UNIQUE,
  schedule   text NOT NULL,          -- cron expression, seconds field supported
  handler    text NOT NULL,          -- key in src/scheduler/handlers.js
  enabled    boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- One row per execution: which server ran the task, when, and how it ended.
CREATE TABLE task_runs (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id     integer NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
  server_id   text NOT NULL,
  status      text NOT NULL CHECK (status IN ('running', 'succeeded', 'failed', 'lock_lost')),
  error       text,
  started_at  timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz
);

CREATE INDEX task_runs_task_id_started_at_idx ON task_runs (task_id, started_at DESC);
